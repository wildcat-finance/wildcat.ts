// Regenerate the SDK interfaces from the finalized protocol build, without copying bytecode.
const fs = require("fs");
const path = require("path");

const artifacts = process.argv[2];
if (!artifacts) throw new Error("Usage: node scripts/sync-v2.5-protocol.js <protocol deploy-out>");
const targets = {
  MarketLens: "MarketLensV2_5",
  HooksFactory: "HooksFactoryV2_5",
  HooksFactoryRevolving: "HooksFactoryRevolvingV2_5",
  WildcatMarket: "WildcatMarketV2_5"
};

for (const [source, target] of Object.entries(targets)) {
  const { abi } = JSON.parse(
    fs.readFileSync(path.join(artifacts, `${source}.sol`, `${source}.json`))
  );
  const structs = new Map();
  const type = (arg) => {
    if (!arg.type.startsWith("tuple")) return arg.type;
    const name = arg.internalType
      .replace(/^struct /, "")
      .replace(/\[.*$/, "")
      .replaceAll(".", "_");
    const fields = arg.components.map((field) => `    ${type(field)} ${field.name};`).join("\n");
    const definition = `  struct ${name} {\n${fields}\n  }`;
    if (structs.has(name) && structs.get(name) !== definition)
      throw new Error(`Conflicting ${name}`);
    structs.set(name, definition);
    return name + arg.type.slice(5);
  };
  const parameter = (arg, location) => {
    const reference = arg.type.startsWith("tuple") || /\[|^(bytes|string)$/.test(arg.type);
    return `${type(arg)}${reference && location ? ` ${location}` : ""}${
      arg.indexed ? " indexed" : ""
    }${arg.name ? ` ${arg.name}` : ""}`;
  };
  const declarations = abi
    .filter(({ type }) => ["function", "event", "error"].includes(type))
    .map((item) => {
      const inputs = item.inputs
        .map((arg) => parameter(arg, item.type === "function" ? "calldata" : ""))
        .join(", ");
      if (item.type !== "function") return `  ${item.type} ${item.name}(${inputs});`;
      const mutability = item.stateMutability === "nonpayable" ? "" : ` ${item.stateMutability}`;
      const outputs = item.outputs.length
        ? ` returns (${item.outputs.map((arg) => parameter(arg, "memory")).join(", ")})`
        : "";
      return `  function ${item.name}(${inputs}) external${mutability}${outputs};`;
    });
  fs.writeFileSync(
    path.join(__dirname, "..", "contracts", `${target}.sol`),
    `// SPDX-License-Identifier: MIT\n// Generated by scripts/sync-v2.5-protocol.js from the Sepolia v2.5.5 deploy profile.\npragma solidity ^0.8.20;\n\ninterface ${target} {\n${[
      ...structs.values(),
      ...declarations
    ].join("\n\n")}\n}\n`
  );
  console.log(`Wrote contracts/${target}.sol`);
}
