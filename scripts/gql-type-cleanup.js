const { createHash } = require("crypto");
const { writeFileSync, readFileSync, existsSync } = require("fs");
const path = require("path");
const { Project, SyntaxKind } = require("ts-morph");
const { getProgressBar } = require("./logs");
const GRAPHQL_TS_PATH = path.join(__dirname, "../src/gql/graphql.ts");

const CODEGEN_YML_PATH = path.join(__dirname, "../codegen.yml");
const SCHEMA_JSON_PATH = path.join(__dirname, "schema.json");
const GQL_CACHE_PATH = path.join(__dirname, ".gql-cache");
const GQL_FRAGMENTS_PATH = path.join(__dirname, "../gql/fragments.graphql");
const GQL_QUERIES_PATH = path.join(__dirname, "../gql/queries.graphql");

/* ========================================================================== */
/*                           WHAT THIS SCRIPT DOES:                           */
/* ========================================================================== */
// This script is used to clean up the generated types in the graphql.ts file
// which is generated by the graphql-codegen tool.
//
// The default output of graphql-codegen is to inline (almost) all types, which
// results in a LOT of duplicate type literals for types which are already defined.
//
// This script will:
// 1. Make all `__typename` fields required by replacing `{ __typename?:` with `{ __typename:`
//    The API will always return a `__typename` field, so making it mandatory makes the types
//    more consistent.
// 2. Replace all type literals with a type alias if a type alias with the same text
//    already exists.
// 3. Preface return type references with `Subgraph`. Graphql-codegen adds the prefix to the
//    generated type aliases, but not to the return types referencing them.
// 4. Add return types to all hooks that are missing them.

// Replace any instance of:
// `{ __typename?: "SomeStringLiteral" }`
// with
// `{ __typename: "SomeStringLiteral" }`
writeFileSync(
  GRAPHQL_TS_PATH,
  readFileSync(GRAPHQL_TS_PATH, "utf-8").replace(/__typename\?:/g, "__typename:")
);

const relativePath = path.relative(path.join(__dirname, ".."), GRAPHQL_TS_PATH);

console.log(`Replacing duplicate type definitions in ${relativePath}...`);

const DEBUG = process.argv.includes("--debug");

const log = (msg) => DEBUG && console.log(msg);

// Initialize project and source file
const project = new Project();
const sourceFile = project.addSourceFileAtPath(GRAPHQL_TS_PATH);

// Map to store unique type definitions
const typeMap = new Map();
const typeReplacementCounts = new Map();

// Find all type aliases
const typeAliases = sourceFile.getDescendantsOfKind(SyntaxKind.TypeAliasDeclaration);

// Fix use* hooks
let i = 0;

const cleanUpTypeText = (text) => text.replace(/\s/g, "");

const timeElapsedPath = path.join(__dirname, "time-elapsed.txt");
const timer = () => {
  let start = Date.now();
  // Write time elapsed as a new line to ./time-elapsed.txt
  const resetAndLogTimeElapsed = (label) => {
    const elapsed = Date.now() - start;
    start = Date.now();
    writeFileSync(timeElapsedPath, `${label}: ${elapsed}ms\n`, { flag: "a" });
  };
  return resetAndLogTimeElapsed;
};

const checkpoint = timer();

// Gather unique type definitions (by text) in all type aliases
typeAliases.forEach((alias) => {
  const typeNode = alias.getTypeNode();

  if (typeNode) {
    const text = cleanUpTypeText(typeNode.getText());

    if (!typeMap.has(text)) {
      typeMap.set(text, alias.getName());
    }
  }
});
checkpoint("Gathered unique type definitions");

let replacements = 0;
const typeLiterals = sourceFile
  .getDescendantsOfKind(SyntaxKind.TypeLiteral)
  // .filter(node => !node.wasForgotten())
  .map((node) => {
    const parent = node.getParent();
    const text = cleanUpTypeText(node.getText());
    const typeName = typeMap.get(text);
    return {
      node,
      parent,
      typeName
    };
  })
  .filter(
    ({ parent, typeName }) =>
      typeName &&
      !(parent?.getKind() === SyntaxKind.TypeAliasDeclaration && parent.getName() === typeName)
  );

checkpoint("Mapped type literals");

const typeLiteralsProgressBar = getProgressBar(
  "Replacing duplicate type literals",
  typeLiterals.length
);
/**
 *
 * @typedef  { Object } ReplaceNodeParam
 * @property {import('ts-morph').TypeLiteralNode} node
 * @property {import('ts-morph').Node<ts.Node>} parent
 * @property {string} typeName
 * @property {string} text
 *
 * @param {ReplaceNodeParam}
 */
function tryReplaceNode({ node, typeName }) {
  if (!node.wasForgotten()) {
    node.replaceWithText(typeName);
    typeReplacementCounts.set(typeName, (typeReplacementCounts.get(typeName) || 0) + 1);
    replacements++;
  }
  typeLiteralsProgressBar();
}

typeLiterals.forEach(tryReplaceNode);

checkpoint("Replaced duplicate type literals");

console.log(`Replaced ${replacements} inline types with named types.`);
for (const [typeName, count] of typeReplacementCounts.entries()) {
  log(`Replacements for ${typeName}: ${count}`);
}

// Save the modified file

const functions = sourceFile.getDescendantsOfKind(SyntaxKind.FunctionDeclaration);
const functionsToRepair = functions.filter((func) => {
  const name = func.getName();
  return name.startsWith("use") && !func.getReturnTypeNode();
});
checkpoint("Found functions to repair");

const repairReturnTypesProgressBar = getProgressBar(
  `Repairing return types for hooks...`,
  functionsToRepair.length
);
for (const func of functionsToRepair) {
  const name = func.getName();
  const baseTypeName = name.replace("use", "");
  const [queryKind, queryName] = [.../(?<=(.+))((?:Suspense|Lazy)?Query)$/.exec(baseTypeName)];
  const returnTypeName = baseTypeName + "HookResult";
  const returnTypeDef = typeAliases.find((alias) => {
    const aliasName = alias.getName();
    return aliasName === returnTypeName;
  });
  const queryType = `Subgraph${queryName}Query`;
  const variablesType = `Subgraph${queryName}QueryVariables`;
  const returnType = `Apollo.${queryKind.includes("Suspense") ? "Use" : ""}${queryKind}Result${
    queryKind.includes("Lazy") ? "Tuple" : ""
  }<${queryType}, ${variablesType}>`;
  func.setReturnType(returnTypeName);
  returnTypeDef.setType(returnType);
  repairReturnTypesProgressBar();
}
checkpoint("Repaired return types");
console.log(`Repaired return types for ${functionsToRepair.length} hooks.`);
console.log(`Saving ${relativePath}...`);
sourceFile.saveSync();

function generateFileChecksum(filePath) {
  return createHash("md5").update(readFileSync(filePath), "utf8").digest("hex");
}

function updateChecksums() {
  const currentChecksums = [
    generateFileChecksum(CODEGEN_YML_PATH),
    generateFileChecksum(SCHEMA_JSON_PATH),
    generateFileChecksum(GQL_FRAGMENTS_PATH),
    generateFileChecksum(GQL_QUERIES_PATH),
    generateFileChecksum(GRAPHQL_TS_PATH)
  ].join("\n");
  writeFileSync(GQL_CACHE_PATH, currentChecksums);
  checkpoint("Saved file");
}

updateChecksums();
