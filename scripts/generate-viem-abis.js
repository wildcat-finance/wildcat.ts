const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const specs = require("./viem-abi-specs.json");
const outputPath = path.join(root, "src/abi/generated.ts");

const filterAbi = (abi, spec) => {
  const types = new Set(spec.types ?? ["function"]);
  const names = spec.names ? new Set(spec.names) : undefined;
  return abi.filter((item) => {
    if (!types.has(item.type)) return false;
    if (names && !names.has(item.name)) return false;
    return true;
  });
};

const artifactAbi = (artifactPath) => {
  const resolvedPath = path.join(root, artifactPath);
  const artifact = JSON.parse(fs.readFileSync(resolvedPath, "utf8"));
  return artifact.abi;
};

const chunks = [
  "/* Autogenerated file. Do not edit manually. */",
  "/* eslint-disable */",
  "",
  'import type { Abi } from "viem";',
  ""
];

for (const spec of specs) {
  const abi = filterAbi(artifactAbi(spec.artifact), spec);
  chunks.push(`export const ${spec.exportName} = ${JSON.stringify(abi, null, 2)} as const satisfies Abi;`);
  chunks.push("");
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `${chunks.join("\n")}\n`);
console.log(`Wrote ${path.relative(root, outputPath)}`);
